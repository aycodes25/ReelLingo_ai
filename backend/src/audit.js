/**
 * Admin audit trail: every change an admin makes (plans, prices, settings, users, minutes, payments…) is written
 * down with who made it, when, and what they sent. Secrets in the request are never stored.
 */

const SECRET_KEY = /pass|secret|token|key|authorization/i;
const MAX_TEXT = 4000;

export function redact(value, depth = 0) {
  if (value === null || typeof value !== "object") return typeof value === "string" ? value.slice(0, 500) : value;
  if (depth > 4) return "…";
  if (Array.isArray(value)) return value.slice(0, 50).map((item) => redact(item, depth + 1));
  return Object.fromEntries(Object.entries(value).slice(0, 80).map(([key, item]) => [key, SECRET_KEY.test(key) ? "[hidden]" : redact(item, depth + 1)]));
}

export async function writeAudit({ adminId, adminEmail, action, target = "", details = {} }) {
  try {
    await query(
      "INSERT INTO admin_audit (admin_id, admin_email, action, target, details) VALUES ($1, $2, $3, $4, $5)",
      [adminId || null, adminEmail || null, String(action).slice(0, 200), String(target).slice(0, 300), JSON.stringify(redact(details)).slice(0, MAX_TEXT)],
    );
  } catch (error) {
    // The change itself already happened; losing the note must be loud, but it must not undo or block the work.
    logger.error({ err: error, action }, "Could not write the admin audit log (is the admin_audit table created? Run backend/sql/schema.sql)");
  }
}

// Reading a customer's personal or payment details is also recorded (who looked, and when). Plain lists and
// dashboards are not: they are opened constantly and would drown out the changes.
const VIEWED_ROUTES = new Set(["/admin/users/:userId", "/admin/usage/users/:userId", "/admin/payments"]);

/**
 * Express middleware for the admin area: after any successful change (POST, PUT, PATCH, DELETE), and after an
 * admin opens a customer's details or the payment list, it writes an audit row *before* the reply goes out.
 * A handler can add context with `response.locals.audit = { before }`.
 */
export function auditAdminChanges(request, response, next) {
  const end = response.end.bind(response);
  let written = false;
  response.end = (...args) => {
    const routePath = request.route?.path || request.path;
    const isChange = !["GET", "HEAD", "OPTIONS"].includes(request.method);
    const isView = request.method === "GET" && VIEWED_ROUTES.has(routePath);
    if (written || response.statusCode >= 400 || !(isChange || isView)) return end(...args);
    written = true;
    void writeAudit({
      adminId: request.userId,
      adminEmail: request.user?.email,
      action: `${isView ? "VIEW " : ""}${request.method} ${request.baseUrl}${routePath}`,
      target: JSON.stringify(request.params || {}),
      details: isView ? { query: request.query } : { body: request.body, query: request.query, ...(response.locals.audit || {}) },
    }).finally(() => end(...args));
    return response;
  };
  next();
}

/** Deletes audit entries older than the retention setting, so the log can't grow forever. */
export async function purgeOldAudit(now = new Date()) {
  const cutoff = dbTime(new Date(now.getTime() - config.auditRetentionDays * 86400000));
  const result = await query("DELETE FROM admin_audit WHERE created_at < $1", [cutoff]);
  return result.rowCount;
}

/**
 * Optional Postgres triggers (backend/sql/audit-triggers.sql, run by hand in the Supabase SQL Editor) that record
 * changes made straight in the database, outside this app: edits in the Supabase table editor or SQL editor.
 * The app names its own connections "reellingo-api" so its changes, which it already logs, aren't written twice.
 */
export const AUDITED_TABLES = [
  { table: "plans", when: "INSERT OR UPDATE OR DELETE" },
  { table: "app_settings", when: "INSERT OR UPDATE OR DELETE" },
  { table: "subscriptions", when: "INSERT OR UPDATE OR DELETE" },
  { table: "payments", when: "INSERT OR UPDATE OR DELETE" },
  { table: "minute_ledger", when: "INSERT OR UPDATE OR DELETE" },
  { table: "profiles", when: "UPDATE OF is_admin, disabled" },
];

export function auditTriggersSql() {
  const lines = [
    "-- OPTIONAL: records changes made directly in Supabase (table editor, SQL editor) in the admin audit log.",
    "-- Generated by `npm run sql` — do not edit by hand. Needs backend/sql/schema.sql to have been run first.",
    "-- Run it yourself: Supabase dashboard → SQL Editor → New query → paste this file → Run. Safe to run more than once.",
    "-- Changes made by the ReelLingo app itself are skipped here because the app already logs them.",
    "",
    "BEGIN;",
    "",
    "CREATE OR REPLACE FUNCTION public.reellingo_audit_change() RETURNS trigger",
    "LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$",
    "DECLARE",
    "  changed json := CASE WHEN TG_OP = 'DELETE' THEN row_to_json(OLD) ELSE row_to_json(NEW) END;",
    "BEGIN",
    "  IF current_setting('application_name', true) = 'reellingo-api' THEN",
    "    RETURN COALESCE(NEW, OLD);",
    "  END IF;",
    "  INSERT INTO public.admin_audit (admin_id, admin_email, action, target, details)",
    "  VALUES (",
    "    'database',",
    "    session_user,",
    "    TG_OP || ' ' || TG_TABLE_NAME,",
    "    COALESCE(changed->>'code', changed->>'key', changed->>'reference', changed->>'user_id', changed->>'billing_id', ''),",
    "    left(json_build_object('before', CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE row_to_json(OLD) END, 'after', CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE row_to_json(NEW) END)::text, 8000)",
    "  );",
    "  RETURN COALESCE(NEW, OLD);",
    "END $$;",
    "",
    "REVOKE ALL ON FUNCTION public.reellingo_audit_change() FROM PUBLIC, anon, authenticated;",
    "",
  ];
  for (const { table, when } of AUDITED_TABLES) {
    lines.push(
      `DROP TRIGGER IF EXISTS reellingo_audit ON public.${table};`,
      `CREATE TRIGGER reellingo_audit AFTER ${when} ON public.${table} FOR EACH ROW EXECUTE FUNCTION public.reellingo_audit_change();`,
      "",
    );
  }
  lines.push("COMMIT;", "");
  return lines.join("\n");
}

export async function listAudit({ limit = 100, offset = 0, search = "" } = {}) {
  const like = `%${String(search).toLowerCase()}%`;
  const rows = search
    ? await many("SELECT * FROM admin_audit WHERE LOWER(action) LIKE $1 OR LOWER(COALESCE(admin_email, '')) LIKE $1 OR LOWER(COALESCE(target, '')) LIKE $1 ORDER BY id DESC LIMIT $2 OFFSET $3", [like, limit, offset])
    : await many("SELECT * FROM admin_audit ORDER BY id DESC LIMIT $1 OFFSET $2", [limit, offset]);
  return rows.map((row) => {
    let details = {};
    try {
      details = JSON.parse(row.details || "{}");
    } catch {
      details = { raw: row.details };
    }
    return {
      id: Number(row.id), admin_id: row.admin_id, admin_email: row.admin_email || "", action: row.action, target: row.target || "", details,
      created_at: row.created_at instanceof Date ? row.created_at.toISOString() : row.created_at,
    };
  });
}

